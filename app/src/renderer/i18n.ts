import { create } from 'zustand';

/** 界面语言（简体中文 / English），localStorage 持久化 */
export type Locale = 'zh' | 'en';

interface LocaleState {
  locale: Locale;
  setLocale: (l: Locale) => void;
}

function initLocale(): Locale {
  try {
    return localStorage.getItem('novelEditor.locale') === 'en' ? 'en' : 'zh';
  } catch {
    return 'zh';
  }
}

export const useLocale = create<LocaleState>(set => ({
  locale: initLocale(),
  setLocale: l => {
    try { localStorage.setItem('novelEditor.locale', l); } catch { /* 存储不可用时忽略 */ }
    try { document.documentElement.lang = l === 'en' ? 'en' : 'zh-CN'; } catch { /* ignore */ }
    set({ locale: l });
  },
}));

